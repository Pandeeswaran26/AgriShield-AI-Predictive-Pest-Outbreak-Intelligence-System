# ── Auth Helper ─────────────────────────────────────────────────────────────

def _get_user_id(db: Session, authorization: Optional[str] = None) -> Optional[int]:
    if not authorization or not authorization.startswith("Bearer "):
        return None
    token = authorization.split(" ", 1)[1].strip()
    if not token or is_token_revoked(db, token):
        return None
    try:
        payload = decode_token(token)
        email = payload.get("sub")
        if email:
            user = get_user_by_email(db, email)
            return user.id if user else None
    except Exception:
        return None
    return None


# ── Pydantic Schemas ────────────────────────────────────────────────────────

class FarmerActionCreate(BaseModel):
    plant_id: Optional[int] = None
    prediction_id: Optional[int] = None
    action_type: str                         # Irrigation | Fertilizer | Chemical Spray | Biological Treatment | Scouting | No Action
    description: Optional[str] = None
    product_used: Optional[str] = None
    dosage: Optional[str] = None
    performed_at: Optional[datetime] = None  # ISO 8601; defaults to now


class FarmerActionResponse(BaseModel):
    id: int
    action_type: str
    description: Optional[str]
    product_used: Optional[str]
    dosage: Optional[str]
    plant_id: Optional[int]
    prediction_id: Optional[int]
    performed_at: Optional[datetime]
    created_at: Optional[datetime]

    class Config:
        from_attributes = True


class FollowUpCreate(BaseModel):
    farmer_action_id: int
    plant_id: Optional[int] = None
    days_after_action: Optional[int] = None
    observed_condition: str                  # Improved | Stable | Worsened | Pest Eradicated | Recurrence
    severity_change: Optional[str] = None   # Better | Same | Worse
    notes: Optional[str] = None


# ── Existing History Routes ──────────────────────────────────────────────────

@router.get("/history", response_model=HistoryResponse)
@router.get("/history/", response_model=HistoryResponse)
def history(
    authorization: Optional[str] = Header(None),
    db: Session = Depends(get_db)
):
    user_id = _get_user_id(db, authorization)
    items = get_all_predictions(db, user_id=user_id)
    return {"items": items, "total": len(items)}


@router.delete("/history/{prediction_id}")
def remove_prediction(
    prediction_id: int,
    authorization: Optional[str] = Header(None),
    db: Session = Depends(get_db)
):
    user_id = _get_user_id(db, authorization)
    prediction = delete_prediction(db, prediction_id, user_id=user_id)
    if not prediction:
        raise HTTPException(status_code=404, detail="Prediction not found or permission denied")
    return {"message": "Prediction deleted successfully"}


@router.get("/history/export")
def export_history(db: Session = Depends(get_db)):
    rows = get_all_predictions(db)
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Crop", "Pest", "Location", "Risk", "Confidence", "Pest Value", "Date"])
    for row in rows:
        writer.writerow([
            row.crop, row.pest_name, row.location,
            row.risk_level, row.confidence, row.pest_value, row.prediction_date
        ])
    output.seek(0)
    return StreamingResponse(
        iter([output.getvalue()]),
        media_type="text/csv",
        headers={"Content-Disposition": "attachment; filename=prediction_history.csv"}
    )


# ── Phase 5: Farmer Action Feedback Loop ────────────────────────────────────

@router.post("/api/farmer-actions", response_model=FarmerActionResponse, status_code=201)
def log_farmer_action(
    payload: FarmerActionCreate,
    authorization: Optional[str] = Header(None),
    db: Session = Depends(get_db),
):
    """
    Records a farmer action taken in response to an AgriShield recommendation.
    E.g., "Applied Chlorpyrifos 2L/acre on 2026-09-22 for Bollworm outbreak."
    """
    valid_action_types = {
        "Irrigation", "Fertilizer", "Chemical Spray",
        "Biological Treatment", "Scouting", "No Action", "Other"
    }
    if payload.action_type not in valid_action_types:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid action_type. Must be one of: {sorted(valid_action_types)}"
        )

    user_id = _get_user_id(db, authorization)

    action = FarmerAction(
        user_id=user_id,
        plant_id=payload.plant_id,
        prediction_id=payload.prediction_id,
        action_type=payload.action_type,
        description=payload.description,
        product_used=payload.product_used,
        dosage=payload.dosage,
        performed_at=payload.performed_at or datetime.now(timezone.utc),
    )
    db.add(action)
    db.commit()
    db.refresh(action)
    return action


@router.get("/api/farmer-actions")
def list_farmer_actions(
    plant_id: Optional[int] = None,
    authorization: Optional[str] = Header(None),
    db: Session = Depends(get_db),
):
    """Returns farmer actions, optionally filtered by plant_id."""
    user_id = _get_user_id(db, authorization)
    query = db.query(FarmerAction)
    if user_id:
        query = query.filter(FarmerAction.user_id == user_id)
    if plant_id:
        query = query.filter(FarmerAction.plant_id == plant_id)
    actions = query.order_by(desc(FarmerAction.created_at)).limit(50).all()
    return {
        "actions": [
            {
                "id": a.id,
                "action_type": a.action_type,
                "description": a.description,
                "product_used": a.product_used,
                "dosage": a.dosage,
                "plant_id": a.plant_id,
                "prediction_id": a.prediction_id,
                "performed_at": a.performed_at.isoformat() if a.performed_at else None,
                "created_at": a.created_at.isoformat() if a.created_at else None,
            }
            for a in actions
        ],
        "total": len(actions),
    }


@router.post("/api/follow-up", status_code=201)
def record_follow_up(
    payload: FollowUpCreate,
    db: Session = Depends(get_db),
):
    """
    Records a post-treatment crop health outcome so AgriShield can track
    the effectiveness of its recommendations over time.
    """
    valid_conditions = {"Improved", "Stable", "Worsened", "Pest Eradicated", "Recurrence"}
    if payload.observed_condition not in valid_conditions:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid observed_condition. Must be one of: {sorted(valid_conditions)}"
        )

    # Verify the referenced farmer action exists
    action = db.query(FarmerAction).filter(FarmerAction.id == payload.farmer_action_id).first()
    if not action:
        raise HTTPException(status_code=404, detail=f"FarmerAction {payload.farmer_action_id} not found")

    outcome = FollowUpOutcome(
        farmer_action_id=payload.farmer_action_id,
        plant_id=payload.plant_id or action.plant_id,
        days_after_action=payload.days_after_action,
        observed_condition=payload.observed_condition,
        severity_change=payload.severity_change,
        notes=payload.notes,
    )
    db.add(outcome)
    db.commit()
    db.refresh(outcome)
    return {
        "id": outcome.id,
        "farmer_action_id": outcome.farmer_action_id,
        "observed_condition": outcome.observed_condition,
        "severity_change": outcome.severity_change,
        "days_after_action": outcome.days_after_action,
        "recorded_at": outcome.recorded_at.isoformat() if outcome.recorded_at else None,
        "message": "Follow-up outcome recorded successfully",
    }


@router.get("/api/fields/{plant_id}/trend")
def get_field_trend(
    plant_id: int,
    authorization: Optional[str] = Header(None),
    db: Session = Depends(get_db),
):
    """
    Returns 7-day and 30-day risk trend analysis for a specific field (plant).
    Includes consecutive high-risk day counter and action history.
    """
    now = datetime.now(timezone.utc)
    day_7_ago = now - timedelta(days=7)
    day_30_ago = now - timedelta(days=30)

    # Recent predictions for this plant
    all_history = (
        db.query(PredictionHistory)
        .filter(PredictionHistory.plant_id == plant_id)
        .order_by(desc(PredictionHistory.prediction_date))
        .limit(60)
        .all()
    )

    def _to_risk_score(r: str) -> int:
        return {"High": 3, "Medium": 2, "Low": 1}.get(r, 1)

    history_7d = [h for h in all_history if h.prediction_date and h.prediction_date >= day_7_ago]
    history_30d = [h for h in all_history if h.prediction_date and h.prediction_date >= day_30_ago]

    # Consecutive high-risk days (most-recent streak)
    consecutive_high = 0
    for h in all_history:
        if h.risk_level and h.risk_level.lower() == "high":
            consecutive_high += 1
        else:
            break

    # Trend direction based on 7d moving average vs prior week
    if len(history_7d) >= 2:
        first_half = history_7d[len(history_7d) // 2:]
        second_half = history_7d[:len(history_7d) // 2]
        avg_first = sum(_to_risk_score(h.risk_level or "Low") for h in first_half) / max(len(first_half), 1)
        avg_second = sum(_to_risk_score(h.risk_level or "Low") for h in second_half) / max(len(second_half), 1)
        if avg_second > avg_first + 0.3:
            trend_direction = "INCREASING"
            trend_icon = "↗"
        elif avg_second < avg_first - 0.3:
            trend_direction = "DECREASING"
            trend_icon = "↘"
        else:
            trend_direction = "STABLE"
            trend_icon = "→"
    else:
        trend_direction = "INSUFFICIENT_DATA"
        trend_icon = "–"

    # Recent farmer actions for this field
    recent_actions = (
        db.query(FarmerAction)
        .filter(FarmerAction.plant_id == plant_id)
        .order_by(desc(FarmerAction.created_at))
        .limit(10)
        .all()
    )

    return {
        "plant_id": plant_id,
        "analysis_timestamp": now.isoformat(),
        "trend_7d": {
            "direction": trend_direction,
            "icon": trend_icon,
            "predictions_count": len(history_7d),
            "high_risk_count": sum(1 for h in history_7d if (h.risk_level or "").lower() == "high"),
            "medium_risk_count": sum(1 for h in history_7d if (h.risk_level or "").lower() == "medium"),
            "low_risk_count": sum(1 for h in history_7d if (h.risk_level or "").lower() == "low"),
        },
        "trend_30d": {
            "predictions_count": len(history_30d),
            "high_risk_count": sum(1 for h in history_30d if (h.risk_level or "").lower() == "high"),
            "medium_risk_count": sum(1 for h in history_30d if (h.risk_level or "").lower() == "medium"),
            "low_risk_count": sum(1 for h in history_30d if (h.risk_level or "").lower() == "low"),
        },
        "consecutive_high_risk_days": consecutive_high,
        "recent_predictions": [
            {
                "id": h.id,
                "date": h.prediction_date.isoformat() if h.prediction_date else None,
                "risk_level": h.risk_level,
                "risk_score": h.confidence,
                "top_pest": h.pest_name,
                "growth_stage": h.growth_stage,
            }
            for h in history_7d[:7]
        ],
        "recent_actions": [
            {
                "id": a.id,
                "action_type": a.action_type,
                "description": a.description,
                "performed_at": a.performed_at.isoformat() if a.performed_at else None,
            }
            for a in recent_actions
        ],
    }


