@router.get("/api/model/evaluation")
def get_model_evaluation(db: Session = Depends(get_db)):
    """
    Returns the latest model benchmark report for the Research & Model Monitoring dashboard.
    Reads from ml/reports/model_benchmark_report.json generated by model_benchmark.py.
    """
    if _BENCHMARK_REPORT.exists():
        with open(_BENCHMARK_REPORT, "r") as f:
            report = json.load(f)
        return {
            "source": "ml/reports/model_benchmark_report.json",
            "report": report,
            "status": "Available",
        }
    else:
        # Return descriptive stub if benchmark hasn't been run yet
        return {
            "source": "Not yet generated",
            "status": "Pending — run `python ml/training/model_benchmark.py` to generate",
            "report": {
                "benchmark_timestamp": None,
                "models_compared": [],
                "best_model": None,
                "calibration": None,
                "note": "Run the model benchmark pipeline to populate this dashboard.",
            },
        }